// Element-specific series that need element appended
const elementSpecificSeries = new Set([
    "covenanter",
    "typhon",
    "griffin",
]);

export function getModImage(modName: string, element?: string): string {
    console.log('🔍 Looking up image for:', modName, 'Element:', element);

    // Extract base name - remove variant suffixes if they appear after the main name
    // e.g., "Blaze Inspo" → check "Blaze", "Prime Morale" → check "Prime"
    let baseName = modName;

    // First try exact match
    let series = modNameToImageSeries[modName];

    // If no exact match, try to extract base name (first word or two)
    if (!series) {
        const words = modName.split(' ');
        // Try progressively shorter names
        for (let i = words.length; i > 0; i--) {
            const testName = words.slice(0, i).join(' ');
            if (modNameToImageSeries[testName]) {
                series = modNameToImageSeries[testName];
                baseName = testName;
                break;
            }
        }
    }

    if (!series) {
        console.log('❌ No series mapping found for:', modName);
        return 'https://picsum.photos/seed/mod-placeholder/200/100';
    }

    console.log('✓ Found series:', series);

    // If series needs element, append it
    if (elementSpecificSeries.has(series) && element) {
        const elementKey = `${series}-${element.toLowerCase()}`;
        if (modImages[elementKey]) {
            console.log('✓ Using element-specific image:', elementKey);
            return modImages[elementKey];
        }
    }

    // Try to use series directly
    if (modImages[series]) {
        console.log('✓ Using series image:', series);
        return modImages[series];
    }

    // Fallback
    console.log('⚠️ No image found, using fallback');
    return 'https://picsum.photos/seed/mod-placeholder/200/100';
}
